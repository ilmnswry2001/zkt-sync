CREATE TYPE public.form_kind AS ENUM ('attendance','overtime','leave');
CREATE TYPE public.form_status AS ENUM ('pending_manager','pending_ceo','pending_execution','executed','rejected');
CREATE TYPE public.form_role AS ENUM ('dept_manager','ceo','executor');

CREATE TABLE public.form_role_assignments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL,
  role public.form_role NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, role)
);
GRANT SELECT ON public.form_role_assignments TO authenticated;
GRANT ALL ON public.form_role_assignments TO service_role;
ALTER TABLE public.form_role_assignments ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.has_form_role(_user_id uuid, _role public.form_role)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.form_role_assignments WHERE user_id = _user_id AND role = _role)
$$;
REVOKE ALL ON FUNCTION public.has_form_role(uuid, public.form_role) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.has_form_role(uuid, public.form_role) TO authenticated, service_role;

CREATE POLICY "read form roles" ON public.form_role_assignments FOR SELECT TO authenticated USING (true);
CREATE POLICY "admin manage form roles" ON public.form_role_assignments FOR ALL TO authenticated
  USING (is_admin(auth.uid())) WITH CHECK (is_admin(auth.uid()));

CREATE TABLE public.department_managers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  department_id uuid NOT NULL REFERENCES public.departments(id) ON DELETE CASCADE,
  user_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (department_id, user_id)
);
GRANT SELECT ON public.department_managers TO authenticated;
GRANT ALL ON public.department_managers TO service_role;
ALTER TABLE public.department_managers ENABLE ROW LEVEL SECURITY;
CREATE POLICY "read dept managers" ON public.department_managers FOR SELECT TO authenticated USING (true);
CREATE POLICY "admin manage dept managers" ON public.department_managers FOR ALL TO authenticated
  USING (is_admin(auth.uid())) WITH CHECK (is_admin(auth.uid()));

CREATE TABLE public.forms (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  form_no bigint GENERATED BY DEFAULT AS IDENTITY,
  employee_id uuid NOT NULL REFERENCES public.employees(id) ON DELETE CASCADE,
  department_id uuid REFERENCES public.departments(id),
  target_department_id uuid REFERENCES public.departments(id),
  work_date date NOT NULL,
  kind public.form_kind NOT NULL DEFAULT 'attendance',
  day_status public.day_status,
  overtime_hours numeric NOT NULL DEFAULT 0,
  check_in time,
  check_out time,
  reason text NOT NULL,
  status public.form_status NOT NULL DEFAULT 'pending_manager',
  created_by uuid,
  manager_approved_by uuid,
  manager_approved_at timestamptz,
  ceo_approved_by uuid,
  ceo_approved_at timestamptz,
  executed_by uuid,
  executed_at timestamptz,
  rejected_by uuid,
  rejected_at timestamptz,
  rejection_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_forms_employee ON public.forms(employee_id, work_date);
CREATE INDEX idx_forms_status ON public.forms(status);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.forms TO authenticated;
GRANT ALL ON public.forms TO service_role;
ALTER TABLE public.forms ENABLE ROW LEVEL SECURITY;

CREATE POLICY "read forms" ON public.forms FOR SELECT TO authenticated USING (true);
CREATE POLICY "create forms" ON public.forms FOR INSERT TO authenticated
  WITH CHECK (created_by = auth.uid());
CREATE POLICY "process forms" ON public.forms FOR UPDATE TO authenticated
  USING (
    has_role(auth.uid(), 'admin') OR has_role(auth.uid(), 'hr')
    OR has_form_role(auth.uid(), 'dept_manager') OR has_form_role(auth.uid(), 'ceo')
    OR has_form_role(auth.uid(), 'executor')
    OR (created_by = auth.uid() AND status = 'pending_manager')
  )
  WITH CHECK (
    has_role(auth.uid(), 'admin') OR has_role(auth.uid(), 'hr')
    OR has_form_role(auth.uid(), 'dept_manager') OR has_form_role(auth.uid(), 'ceo')
    OR has_form_role(auth.uid(), 'executor')
    OR (created_by = auth.uid() AND status = 'pending_manager')
  );
CREATE POLICY "delete own pending forms" ON public.forms FOR DELETE TO authenticated
  USING (is_admin(auth.uid()) OR (created_by = auth.uid() AND status = 'pending_manager'));

CREATE TRIGGER trg_forms_upd BEFORE UPDATE ON public.forms
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE public.form_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  form_id uuid NOT NULL REFERENCES public.forms(id) ON DELETE CASCADE,
  action text NOT NULL,
  note text,
  actor uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_form_events_form ON public.form_events(form_id, created_at);
GRANT SELECT, INSERT ON public.form_events TO authenticated;
GRANT ALL ON public.form_events TO service_role;
ALTER TABLE public.form_events ENABLE ROW LEVEL SECURITY;
CREATE POLICY "read form events" ON public.form_events FOR SELECT TO authenticated USING (true);
CREATE POLICY "insert form events" ON public.form_events FOR INSERT TO authenticated
  WITH CHECK (actor = auth.uid());

ALTER TABLE public.attendance_day_status ADD COLUMN IF NOT EXISTS overtime_hours numeric NOT NULL DEFAULT 0;

DROP POLICY IF EXISTS "staff manage day status" ON public.attendance_day_status;
CREATE POLICY "staff manage day status" ON public.attendance_day_status FOR ALL TO authenticated
  USING (
    has_role(auth.uid(), 'admin') OR has_role(auth.uid(), 'hr') OR has_role(auth.uid(), 'supervisor')
    OR has_role(auth.uid(), 'data_entry') OR has_form_role(auth.uid(), 'executor')
  )
  WITH CHECK (
    has_role(auth.uid(), 'admin') OR has_role(auth.uid(), 'hr') OR has_role(auth.uid(), 'supervisor')
    OR has_role(auth.uid(), 'data_entry') OR has_form_role(auth.uid(), 'executor')
  );